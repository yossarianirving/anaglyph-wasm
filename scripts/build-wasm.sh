#!/usr/bin/env bash
# Build pkg/ (wasm-bindgen `--target web` output) reproducibly.
#
# The generated JS glue and the .wasm must travel together: wasm-bindgen
# refuses mismatched glue/wasm at init, so the CLI version is pinned to the
# exact crate version below and checked before anything is rebuilt.
#
# Usage: scripts/build-wasm.sh [--scalar]
#   --scalar  baseline build without SIMD (target-cpu=mvp), same as the old
#             npm run build:wasm:scalar
set -euo pipefail
cd "$(dirname "$0")/.."

PINNED_WASM_BINDGEN="0.2.130"

if ! command -v wasm-bindgen >/dev/null 2>&1; then
  echo "error: wasm-bindgen CLI not found (cargo install wasm-bindgen-cli --version ${PINNED_WASM_BINDGEN})" >&2
  exit 1
fi
actual="$(wasm-bindgen --version | awk '{print $NF}')"
if [ "${actual}" != "${PINNED_WASM_BINDGEN}" ]; then
  echo "error: wasm-bindgen CLI ${actual} != pinned ${PINNED_WASM_BINDGEN}" >&2
  echo "       the pkg/ glue must be generated by the pinned CLI:" >&2
  echo "       cargo install wasm-bindgen-cli --version ${PINNED_WASM_BINDGEN} --force" >&2
  exit 1
fi

if [ "${1:-}" = "--scalar" ]; then
  echo "==> cargo build (scalar: target-cpu=mvp +reference-types)"
  RUSTFLAGS="-C target-cpu=mvp -C target-feature=+reference-types" \
    cargo build --target wasm32-unknown-unknown --release --features gpu --lib
else
  echo "==> cargo build (release, gpu feature)"
  cargo build --target wasm32-unknown-unknown --release --features gpu --lib
fi

echo "==> wasm-bindgen ${actual} -> pkg/"
wasm-bindgen target/wasm32-unknown-unknown/release/anaglyph_wasm.wasm \
  --out-dir pkg --target web
# wasm-bindgen drops a pkg/.gitignore ("*") that would exclude the built
# package from git; committed pkg/ is the distribution contract here.
rm -f pkg/.gitignore

# Optional size pass; skipped when binaryen is not installed so casual
# builds never break. -O3 preserves exports/name section; the reference
# types the build relies on need the explicit enable flag.
if command -v wasm-opt >/dev/null 2>&1; then
  echo "==> wasm-opt -O3 (binaryen found)"
  wasm-opt -O3 --enable-reference-types --enable-bulk-memory \
    pkg/anaglyph_wasm_bg.wasm -o pkg/anaglyph_wasm_bg.wasm
else
  echo "==> wasm-opt not installed, skipping size pass"
fi

echo "done. pkg/ rebuilt — commit it together with Cargo.lock."
